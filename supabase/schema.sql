create schema if not exists nc;

create table if not exists nc.users (
  id            integer generated by default as identity primary key,
  nome          text not null,
  login         text not null,
  email         text not null default '',
  senha         text not null,
  perfil        text not null check (perfil in ('admin', 'gestor', 'qualidade', 'colaborador')),
  ativo         boolean not null default true,
  trocar_senha  boolean not null default false,
  criado_em     text not null,
  ultimo_acesso text
);
create unique index if not exists users_login_ci on nc.users (lower(login));

create table if not exists nc.sessions (
  token   text primary key,
  user_id integer not null references nc.users(id) on delete cascade,
  expira  double precision not null
);
create index if not exists sessions_user on nc.sessions (user_id);

create table if not exists nc.ncs (
  id         text primary key,
  numero     text not null unique,
  status     text not null,
  version    integer not null default 1,
  rev        bigint not null default 0,
  updated_at text not null,
  data       jsonb not null
);
create index if not exists ncs_rev on nc.ncs (rev);

create table if not exists nc.anexos (
  id        text primary key,
  nc_id     text not null references nc.ncs(id) on delete cascade,
  nome      text not null,
  tipo      text not null,
  tamanho   integer not null,
  conteudo  bytea not null,
  criado_em text not null,
  por       text
);
create index if not exists anexos_nc on nc.anexos (nc_id);

create table if not exists nc.kv (
  k text primary key,
  v text not null
);

-- tentativas de login erradas (5 seguidas bloqueiam o IP por 60 s)
create table if not exists nc.login_fails (
  ip    text primary key,
  fails integer not null default 0,
  ate   double precision not null default 0
);

create table if not exists nc.auditoria (
  id       bigint generated by default as identity primary key,
  data     text not null,
  user_id  integer,
  usuario  text not null default '',
  login    text default '',
  tipo     text not null,
  acao     text not null,
  detalhe  text default '',
  ref      text default '',
  ip       text default ''
);
create index if not exists ix_aud_data on nc.auditoria(data);
create index if not exists ix_aud_user on nc.auditoria(user_id);

create table if not exists nc.notificacoes (
  id       bigint generated by default as identity primary key,
  user_id  integer not null,
  data     text not null,
  titulo   text not null,
  texto    text default '',
  nc_id    text default '',
  ref      text default '',
  de       text default '',
  lida     boolean not null default false
);
create index if not exists ix_notif_user on nc.notificacoes(user_id, id);

create table if not exists nc.online (
  user_id  integer primary key,
  visto    double precision not null,
  nome     text not null default '',
  perfil   text not null default ''
);

-- Segurança: o schema "nc" NÃO é exposto pela API pública do Supabase e as tabelas ficam com RLS ligado
-- e sem nenhuma política. Assim, só a Edge Function "api" (que conecta direto no banco) lê e grava os dados;
-- a chave pública (anon) não acessa nada.
alter table nc.users       enable row level security;
alter table nc.sessions    enable row level security;
alter table nc.ncs         enable row level security;
alter table nc.anexos      enable row level security;
alter table nc.kv          enable row level security;
alter table nc.login_fails enable row level security;
alter table nc.auditoria    enable row level security;
alter table nc.notificacoes enable row level security;
alter table nc.online       enable row level security;
revoke all on schema nc from anon, authenticated;
revoke all on all tables in schema nc from anon, authenticated;
